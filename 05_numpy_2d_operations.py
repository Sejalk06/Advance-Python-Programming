import numpy as np

a = np.array([[10, 20], [30, 40]])
b = np.array([[2, 4], [5, 8]])

print("Array A:\n", a)
print("Array B:\n", b)
print("Addition:\n", a + b)
print("Subtraction:\n", a - b)
print("Multiplication:\n", a * b)
print("Division:\n", a / b)
print("Transpose of A:\n", a.T)
print("Exponential of A:\n", np.exp(a))
